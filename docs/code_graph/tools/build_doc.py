"""Assemble docs/code_graph/CODE_GRAPH.md from CODE_GRAPH.src.md, replacing @@name@@ with the Mermaid source of
name.mmd plus a link to name.svg. Run from anywhere."""
import os, re
here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(here, "CODE_GRAPH.src.md"), encoding="utf-8").read()

def block(m):
    name = m.group(1)
    mmd = open(os.path.join(here, name + ".mmd"), encoding="utf-8").read().strip()
    return f"```mermaid\n{mmd}\n```\n\nSVG: [`{name}.svg`]({name}.svg)"

out = re.sub(r"@@(\w+)@@", block, src)
open(os.path.join(here, "CODE_GRAPH.md"), "w", encoding="utf-8").write(
    "<!-- Generated by docs/code_graph/tools/build_doc.py from CODE_GRAPH.src.md and *.mmd; edit those. -->\n" + out)
print("wrote", os.path.join(here, "CODE_GRAPH.md"))
